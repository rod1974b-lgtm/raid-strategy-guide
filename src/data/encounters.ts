export function findEncounter(id: string) {
  return ENCOUNTERS.find((e) => e.id === id);
}

export function encounterToBrief(e: Encounter) {
  return [
    `Name: ${e.name} (${e.mode}${e.affinity ? `, ${e.affinity} affinity` : ""})`,
    `Summary: ${e.summary}`,
    `What wipes teams: ${e.wipes.join("; ")}`,
    `Kill priority: ${e.killOrder.join("; ")}`,
    `Mandatory mechanics: ${e.mechanics.join("; ")}`,
    `Stat checkpoints: ${Object.entries(e.stats).map(([k, v]) => `${k}=${v}`).join(", ")}`,
    `Turn order: ${e.turnOrder.join(" → ")}`,
    `Auto AI presets: ${e.aiPresets.map((p) => `${p.role}: ${p.preset}`).join("; ")}`,
    `Template team: ${e.team.join(", ")}`,
    `Budget route: ${e.budget}`,
    `Gear build order: ${e.gearFirst.join(" → ")}`,
  ].join("\n");
}
